inline void draw(Canvas& canvas, const char* const* sprite, int x, int y,
                 uint8_t scale) {
  for (int row = 0; row < 24; ++row) {
    for (int column = 0; column < 24; ++column) {
      if (sprite[row][column] == '#') {
        canvas.rect(x + column * scale, y + row * scale, scale, scale, true);
      }
    }
  }
}

